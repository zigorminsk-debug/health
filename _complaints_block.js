/* ---------- Утилиты ---------- */
function escHtml(s){ return String(s||'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c])); }
function normText(t){
  return (t||'').toString()
    .toLowerCase()
    .replace(/ё/g,'е')
    .replace(/[^a-zа-я0-9+.,%<>-]+/g,' ')
    .replace(/\s+/g,' ')
    .trim();
}

/* ---------- НЕГАЦИИ ---------- */
// Фразы вроде «боли нет», «нет температуры», «не тошнит», «без тошноты»
// обнуляют соседние ключевые слова.
const NEG_PATTERNS = [
  /нет\s+(сильной\s+|сильн[ауоыяе]+\s+)?(\S+)/g,
  /не\s+(больно|болит|тошнит|кашляю|кашл(я|е)(ю|т)|рв[её]т|знобит|мучает|харкаю|отека(ю|ют)|задыхаюсь|мочусь)/g,
  /без\s+(\S+)/g,
  /отсутствие\s+(\S+)/g,
  /кроме\s+(\S+)/g,
  /(\S+)\s+не\s+беспоко(ит|ят)/g
];

// Маскирует слова рядом с «нет/не/без/отсутствие», заменяя их на «~NEG~»
// чтобы они не попадали в подсчёт.
function stripNegations(text){
  let t = ' '+text+' ';
  // Заменяем распространённые обороты отрицания на маску длины слова
  t = t.replace(/нет\s+([\s\S]{2,40}?)(?=[.!,;?]|$|\bи\b|\bно\b|\bкроме\b|\bа\b|\bтакже\b)/gi, (m,p1)=>{
    return ' ' + p1.replace(/[а-яa-z]+/g, '~NEG~') + ' ';
  });
  t = t.replace(/не\s+([а-яё]+)/gi, (m,w)=>{
    // «не» + глагол/прилагательное
    return '~NEG~';
  });
  t = t.replace(/(?:без|отсутствие)\s+([а-яё]+)/gi, (m,w)=>'~NEG~');
  return t;
}

