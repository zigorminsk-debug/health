/* ---------- ДВИЖОК ВЕРОЯТНОСТЕЙ ---------- */
function scoreCondition(cond, textNorm, ctx){
  let score=0, hits=[], against=0, redHits=[];
  const negText = stripNegations(textNorm);
  function matchAny(arr, weight, label){
    if(!arr) return 0;
    let added = 0;
    for(const re of arr){
      // test against NEG-STRIPPED version (so that «нет температуры» не считается)
      if(re.test(negText)){
        // additional guard: if the same region is inside an area near "нет/не/без" skip
        hits.push(label);
        added += weight;
        break; // one phrase per group = that signal
      }
    }
    return added;
  }
  const c = matchAny(cond.triggers&&cond.triggers.core, 3, 'core');
  const t = matchAny(cond.triggers&&cond.triggers.typical, 2, 'typical');
  const m = matchAny(cond.triggers&&cond.triggers.mild, 1, 'mild');
  const r = matchAny(cond.triggers&&cond.triggers.risk, 1, 'risk');
  // Red flags via legacy field (urgent patterns are already in core/typical)
  // Against patterns
  if(cond.triggers&&cond.triggers.against){
    for(const re of cond.triggers.against){
      if(re.test(negText)) against += 2;
    }
  }
  score = c + t + m + r - against;
  // Compute "max possible" = core*3 + typical*2 + mild*1 + risk*1 (for percent)
  const maxCore    = (cond.triggers&&cond.triggers.core)    ? cond.triggers.core.length*3 : 0;
  const maxTypical = (cond.triggers&&cond.triggers.typical) ? cond.triggers.typical.length*2 : 0;
  const maxMild    = (cond.triggers&&cond.triggers.mild)    ? cond.triggers.mild.length*1 : 0;
  // cap max possible to a reasonable ceiling: 8 points typical + 6 core gives high signal already
  const maxPossible = Math.max(8, Math.min(18, 3 + 2*3 + 1*2 + 1*1 + (cond.urgent?3:0)));
  let pct = Math.max(0, Math.min(100, Math.round(score/maxPossible*100)));
  // Require a threshold: at least 3 points from core/typical (i.e., real clinical signals)
  const clinicalPoints = c + t;
  // For urgent (red-flag) conditions — always show if they have any core hit OR are in urgent-list with at least one specific symptom
  const anyCore = c>0;
  let tier = 'none';
  if(cond.urgent && anyCore) tier='urgent';
  else if(score<3 || clinicalPoints<3) tier='none';
  else if(pct>=65) tier='high';
  else if(pct>=40) tier='med';
  else if(pct>=25) tier='low';
  else tier='none';
  // Urgent: also require clinicalPoints to avoid spurious hits on "боль в груди когда нервничаю" without context
  if(cond.urgent && clinicalPoints<3 && !(t>=3)) tier='none';
  return {cond, score, pct, tier, hits, against, clinicalPoints};
}

function analyzeComplaints(text, ctx){
  ctx = ctx || {};
  if(!text||!text.trim()) return [];
  const norm = normText(text);
  const results = [];
  for(const k of SYMPTOM_KB){
    const s = scoreCondition(k, norm, ctx);
    if(s.tier !== 'none') results.push(s);
  }
  results.sort((a,b)=>{
    const order = {urgent:0, high:1, med:2, low:3, none:4};
    if(order[a.tier]!==order[b.tier]) return order[a.tier]-order[b.tier];
    return b.score-a.score;
  });
  return results;
}

